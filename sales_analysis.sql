--20. Find customers contributing to 80% of total revenue.
WITH customer_sales AS (
    SELECT
        c.customer_id,
        c.customer_name,
        SUM(o.amount) AS customer_revenue
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
    GROUP BY
        c.customer_id,
        c.customer_name
),

cumulative_sales AS (
    SELECT
        customer_id,
        customer_name,
        customer_revenue,
        SUM(customer_revenue) OVER (
            ORDER BY customer_revenue DESC
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS cumulative_revenue
    FROM customer_sales
)

SELECT
    customer_id,
    customer_name,
    customer_revenue,
    cumulative_revenue,
    ROUND(
        cumulative_revenue * 100.0 /
        (SELECT SUM(customer_revenue) FROM customer_sales),
        2
    ) AS cumulative_percentage
FROM cumulative_sales
WHERE cumulative_revenue <= (
    SELECT SUM(customer_revenue) * 0.80
    FROM customer_sales
)
ORDER BY customer_revenue DESC;





