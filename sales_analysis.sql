##Basic & Sales Analysis
--Q1. Find the total revenue generated by the company.
select sum(o.quantity*p.price)as total_revenue
from orders o
join products p
on o.product_id=p.product_id


--Q2. Find the total number of orders placed.
select count(order_id)as total_orders_placed 
from orders 



--Q3. Find the total quantity of products sold.
select sum(quantity)as total_quantity_placed 
from orders 


--Q4. Find the total sales generated by each product.
select p.product_id,p.product_name,sum(o.amount)as sales_generated
from products p 
join orders o
on p.product_id=o.product_id
group by  p.product_id,p.product_name

--Q5. Find the top 5 products based on total revenue.
select p.product_id,p.product_name,sum(o.amount) product_revenue
from products p 
join orders o
on p.product_id=o.product_id
group by  p.product_id,p.product_name
order by product_revenue desc 
limit 5;


##Customer Analysis
--Q6. Find the total amount spent by each customer.
select c.customer_id,c.customer_name,sum(o.amount)as amount_spent
from customers c
join orders o
on c.customer_id=o.customer_id
group by  c.customer_id,c.customer_name
order by  amount_spent desc;


