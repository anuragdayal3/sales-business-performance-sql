--17. Find departments contributing more than 20% of total company revenue.
with department_revenue as(
select d.department_id,d.department_name,sum(o.amount)as depart_revenue
from departments d
join employees e
on d.department_id=e.department_id
join orders o 
on e.employee_id=o.employee_id
group by d.department_id,d.department_name
)
